"""Cross-language JCS+SHA-256 parity tests — Path B step 2.

minitrace-spec v0.3.0 §3.4 pins RFC 8785 (JCS) + SHA-256 and claims the
canonical form is byte-identical across conformant implementations
regardless of programming language. This test falsifies (or fails to
falsify) that claim against two specific implementations:

  - Python `rfc8785` library (used by `adapters/cross_trace.py`)
  - Rust `serde_json_canonicalizer` crate (built into
    `adapters/jcs-oracle/target/release/jcs-oracle`)

The fixtures live in `tests/vectors/canonical-vectors.json`, the
implementation-independent vectors for §3.4 (canonical form and numeric
domain), generated by `tests/vectors/build_canonical_vectors.py`. The Rust
verifier `minitrace-verify` runs the same file in its own test suite.

For each canonical vector we feed identical input bytes to both pipelines and
assert byte-equal canonical output AND equal `sha256:<hex>` digest, both equal
to the values the vector records. For each not-conformant vector we assert the
Python reader refuses it for the recorded reason. A
divergence on any fixture is a research datum: either an
implementation bug to file upstream, or a spec ambiguity to raise
with the specification.

The interesting fixtures are three known-hard cases
(1e-7 / 1e16 / BMP-vs-non-BMP key sort); the rest are cheap sanity
extensions probing other edges (empty containers, deep object/array
nesting, beyond-safe-integer values, negative zero, C0 control-char
escaping, UTF-8-vs-surrogate escape-form equivalence, very large strings).

Prerequisite: a Rust toolchain with the crate's dependencies in the local
cargo cache. The driver builds the oracle itself before first use
(`cargo build --release --offline --locked --manifest-path
adapters/jcs-oracle/Cargo.toml`), so the binary always matches the source
in this tree.

Run:
    python -m pytest adapters/tests/test_jcs_parity.py -v
or:
    python adapters/tests/test_jcs_parity.py
"""
from __future__ import annotations

import hashlib
import json
import pathlib
import subprocess
import sys

import rfc8785

ORACLE_BIN = (
    pathlib.Path(__file__).resolve().parent.parent
    / "jcs-oracle"
    / "target"
    / "release"
    / "jcs-oracle"
)


_ORACLE_MANIFEST = ORACLE_BIN.parent.parent.parent / "Cargo.toml"
_oracle_build_error: str | None = None
_oracle_built = False


def _build_oracle() -> str | None:
    """Build jcs-oracle from this tree's source; return an error or None.

    A binary left in target/ from an earlier source would otherwise answer
    for the current one. cargo returns at once when nothing changed.
    """
    global _oracle_built, _oracle_build_error
    if _oracle_built:
        return _oracle_build_error
    _oracle_built = True
    cmd = ["cargo", "build", "--release", "--offline", "--locked", "--quiet",
           "--manifest-path", str(_ORACLE_MANIFEST)]
    try:
        proc = subprocess.run(cmd, stdout=subprocess.PIPE, stderr=subprocess.PIPE,
                              text=True, check=False, timeout=600)
    except FileNotFoundError:
        _oracle_build_error = "cargo not found; these tests build jcs-oracle from source"
        return _oracle_build_error
    except subprocess.TimeoutExpired:
        _oracle_build_error = f"`{' '.join(cmd)}` did not finish in 600 s"
        return _oracle_build_error
    if proc.returncode != 0 or not ORACLE_BIN.is_file():
        _oracle_build_error = f"`{' '.join(cmd)}` failed (exit {proc.returncode}):\n{proc.stderr}"
    return _oracle_build_error


def _rust_canonical(raw: bytes) -> bytes:
    proc = subprocess.run(
        [str(ORACLE_BIN)],
        input=raw,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        check=False, timeout=300,
    )
    if proc.returncode != 0:
        raise AssertionError(
            f"jcs-oracle failed (exit {proc.returncode}): "
            f"{proc.stderr.decode('utf-8', errors='replace')}"
        )
    return proc.stdout


def _rust_hash(raw: bytes) -> str:
    proc = subprocess.run(
        [str(ORACLE_BIN), "--hash"],
        input=raw,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        check=False, timeout=300,
    )
    if proc.returncode != 0:
        raise AssertionError(
            f"jcs-oracle --hash failed (exit {proc.returncode}): "
            f"{proc.stderr.decode('utf-8', errors='replace')}"
        )
    return proc.stdout.decode("ascii").rstrip("\n")


def _python_canonical(raw: bytes) -> bytes:
    return rfc8785.dumps(json.loads(raw))


def _python_hash(raw: bytes) -> str:
    return f"sha256:{hashlib.sha256(_python_canonical(raw)).hexdigest()}"


VECTORS_FILE = pathlib.Path(__file__).resolve().parent / "vectors" / "canonical-vectors.json"
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent))
from source_reader import trace_json_verdict  # noqa: E402

VECTORS = json.loads(VECTORS_FILE.read_text(encoding="utf-8"))["vectors"]
CANONICAL = [v for v in VECTORS if v["verdict"] == "canonical"]
NOT_CONFORMANT = [v for v in VECTORS if v["verdict"] == "not-conformant"]
_BY_NAME = {v["name"]: v for v in VECTORS}


# ---------------------------------------------------------------------------
# Documented-divergence fixtures.
#
# These are inputs where the two implementations DO NOT agree, by design,
# and the divergence is a defensible-but-different reading of RFC 8785. We
# capture them positively (the divergence IS the assertion) rather than as
# red marks in the parity suite. Each divergence is a candidate for a
# minitrace-spec §3.4 clarification.
# ---------------------------------------------------------------------------

# 2^53 + 1 is the smallest positive integer not exactly representable as
# IEEE 754 binary64.
#   - Python `rfc8785`: raises with "exceeds safe integer domain for JSON
#     floats" — guards against silent precision loss.
#   - Rust `serde_json_canonicalizer`: silently parses to f64 (which
#     quantises 9007199254740993 → 9007199254740992), then emits per
#     ECMA-404. Crate README explicitly documents this behaviour.
# Both are defensible against RFC 8785 (which mandates the f64 numeric
# model but does not mandate guarding). Implication for minitrace v0.3.0
# §3.4: traces containing integer values > 2^53 - 1 would hash
# inconsistently between Python and Rust verifiers. A spec question:
# either constrain trace numeric domain or mandate
# string-encoding for bigints. See test_beyond_safe_int_divergence below.
# The input is vector `beyond_safe_integer` in canonical-vectors.json.


def _assert_vector(v: dict) -> None:
    """A canonical vector: both pipelines reproduce the recorded bytes and digest."""
    raw = v["input"].encode("utf-8")
    _assert_parity(v["name"], raw, v["note"])
    expected = v["canonical"].encode("utf-8")
    if _python_canonical(raw) != expected:
        raise AssertionError(f"[{v['name']}] canonical bytes differ from the vector file")
    if _python_hash(raw) != v["sha256"]:
        raise AssertionError(f"[{v['name']}] digest differs from the vector file")


def _assert_refused(v: dict) -> None:
    """A not-conformant vector: the Python verification path refuses it for
    the recorded reason (numeric domain by value, non-finite, or depth)."""
    _value, got = trace_json_verdict(v["input"])
    if got is None:
        raise AssertionError(f"[{v['name']}] accepted, but the vector says not-conformant ({v['reason']})")
    if got != v["reason"]:
        raise AssertionError(f"[{v['name']}] refused as {got}, vector says {v['reason']}")


def _assert_parity(name: str, raw: bytes, note: str) -> None:
    """Feed `raw` to both pipelines, assert canonical bytes + hash equal."""
    py_canonical = _python_canonical(raw)
    rust_canonical = _rust_canonical(raw)
    if py_canonical != rust_canonical:
        raise AssertionError(
            f"[{name}] CANONICAL DIVERGENCE — {note}\n"
            f"  input : {raw!r}\n"
            f"  python: {py_canonical!r}\n"
            f"  rust  : {rust_canonical!r}\n"
        )
    py_hash = _python_hash(raw)
    rust_hash = _rust_hash(raw)
    if py_hash != rust_hash:
        raise AssertionError(
            f"[{name}] HASH DIVERGENCE despite canonical match — {note}\n"
            f"  canonical: {py_canonical!r}\n"
            f"  python   : {py_hash}\n"
            f"  rust     : {rust_hash}\n"
        )


# ---------------------------------------------------------------------------
# pytest entry points — one function per fixture so pytest -v lists them.
# ---------------------------------------------------------------------------


def _ensure_oracle() -> None:
    """A missing toolchain or a failed build fails the test; it does not skip."""
    err = _build_oracle()
    if err is not None:
        raise AssertionError(err)


def test_canonical_vectors() -> None:
    _ensure_oracle()
    for v in CANONICAL:
        _assert_vector(v)


def test_not_conformant_vectors() -> None:
    for v in NOT_CONFORMANT:
        _assert_refused(v)


def test_escape_form_equivalence() -> None:
    """UTF-8 literal and UTF-16 surrogate-pair escape of U+1D11E converge on
    the literal UTF-8 form (RFC 8785 emits literal UTF-8 for characters that
    need no escape)."""
    a, b = _BY_NAME["escape_equiv_literal"], _BY_NAME["escape_equiv_surrogate"]
    if a["canonical"] != b["canonical"] or a["canonical"].encode("utf-8") != b'{"k":"\xf0\x9d\x84\x9e"}':
        raise AssertionError(f"escape forms do not converge on literal UTF-8: {a['canonical']!r} {b['canonical']!r}")


def test_beyond_safe_int_divergence() -> None:
    """Documented divergence: Python guards, Rust quantises through f64.

    Both behaviours are defensible against RFC 8785 (which mandates the
    f64 numeric model but does not mandate guarding). §3.4's numeric domain
    resolves it at the trace level: the integer literal is not conformant,
    so a verifier refuses it before canonicalising. This test pins that the
    bare JCS layer still quantises, which is why the check must come first.
    """
    _ensure_oracle()
    raw = _BY_NAME["beyond_safe_integer"]["input"].encode("utf-8")
    # Python side: rfc8785 raises ValueError with a recognisable message.
    try:
        _python_canonical(raw)
    except ValueError as e:
        msg = str(e)
        assert "safe integer" in msg.lower() or "exceeds safe integer" in msg, (
            f"Python rfc8785 raised but message changed shape: {msg!r}"
        )
    else:
        raise AssertionError(
            "Python rfc8785 unexpectedly accepted 2^53 + 1; behaviour drifted "
            "from documented guard"
        )
    # Rust side: silently quantises to 9007199254740992 (the nearest f64).
    rust_canonical = _rust_canonical(raw)
    assert rust_canonical == b'{"x":9007199254740992}', (
        f"Rust serde_json_canonicalizer produced unexpected output for "
        f"2^53 + 1: {rust_canonical!r} (expected b'{{\"x\":9007199254740992}}'); "
        f"behaviour drifted from documented f64 quantisation"
    )


# ---------------------------------------------------------------------------
# Standalone runner (matches test_cross_trace.py convention).
# ---------------------------------------------------------------------------


def main() -> int:
    err = _build_oracle()
    if err is not None:
        print(f"FAIL: {err}", file=sys.stderr)
        return 2
    passed = 0
    failed = 0
    checks = [(f"canonical {v['name']}", lambda v=v: _assert_vector(v)) for v in CANONICAL]
    checks += [(f"refused {v['name']}", lambda v=v: _assert_refused(v)) for v in NOT_CONFORMANT]
    checks += [("escape_form_equivalence", test_escape_form_equivalence),
               ("beyond_safe_int_divergence", test_beyond_safe_int_divergence)]
    print(f"Vectors: {VECTORS_FILE.name} ({len(CANONICAL)} canonical, {len(NOT_CONFORMANT)} not-conformant)")
    for label, fn in checks:
        try:
            fn()
            print(f"  PASS  {label}")
            passed += 1
        except Exception as e:  # noqa: BLE001
            print(f"  FAIL  {label}: {e}")
            failed += 1
    print(f"\n{passed} passed, {failed} failed")
    return 0 if failed == 0 else 1


if __name__ == "__main__":
    sys.exit(main())
